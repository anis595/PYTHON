# Crée une fonction nommée "additionner" qui prend DEUX paramètres (par exemple a et b).
# À l'intérieur, elle doit additionner a et b, et retourner le total avec return.
# En dehors de la fonction, appelle-la avec les chiffres 12 et 8,
# et affiche le résultat avec un print.


def addtionner(a, b):
    resultat = a + b
    return resultat


