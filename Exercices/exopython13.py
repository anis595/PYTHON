# Crée une fonction nommée "calculer_double" qui prend un nombre en paramètre,
# le multiplie par 2, et retourne le résultat avec return.
# En dehors de la fonction, appelle-la en lui donnant le chiffre 15,
# et affiche le résultat retourné avec un print.


def calcule_double(nombre):
    resultat = nombre * 2
    return resultat


print(calcule_double(15))
